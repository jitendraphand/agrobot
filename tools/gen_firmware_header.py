#!/usr/bin/env python3
"""Write firmware/lib/agro_core/robot_geometry.h from cad/agrobot_cad/params.py
so that the firmware, the CAD and the simulation can never disagree."""
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "cad"))
from agrobot_cad import params as P   # noqa: E402

OUT = os.path.join(ROOT, "firmware", "lib", "agro_core", "robot_geometry.h")


def m(v):
    return f"{v / 1000.0:.5f}f"


def rad(v):
    return f"{math.radians(v):.6f}f"


def main():
    L = []
    a = L.append
    a("// GENERATED by tools/gen_firmware_header.py from cad/agrobot_cad/params.py")
    a("// Do not edit by hand: change params.py and re-run the generator.")
    a("#pragma once")
    a("")
    a("namespace agro {")
    a("namespace geom {")
    a("// ---- drive base (metres) ----")
    a(f"constexpr float WHEEL_RADIUS = {m(P.WHEEL_R)};")
    a(f"constexpr float TRACK = {m(P.TRACK)};            // wheel centre to wheel centre")
    a(f"constexpr float WHEELBASE = {m(P.WHEELBASE)};")
    a(f"constexpr float ENC_TICKS_PER_REV = {P.MOTOR_ENC_PPR * 4 * P.MOTOR_GEAR_RATIO:.1f}f;   // quadrature x gear ratio")
    a(f"constexpr float MOTOR_NOLOAD_RAD_S = {P.MOTOR_NOLOAD_RPM * 2 * math.pi / 60:.4f}f;")
    a("// ---- arm (metres, robot frame: +X forward, +Y left, +Z up, origin on the ground) ----")
    a(f"constexpr float YAW_X = {m(P.YAW_X)};            // yaw axis position")
    a(f"constexpr float SHOULDER_OFF = {m(P.SHOULDER_X)};     // shoulder axis ahead of the yaw axis")
    a(f"constexpr float SHOULDER_Z = {m(P.SHOULDER_Z)};       // shoulder axis above the ground")
    a(f"constexpr float L1 = {m(P.L1)};")
    a(f"constexpr float L2 = {m(P.L2)};")
    for name, v in (("GRIPPER", P.TCP_GRIPPER), ("PROBE", P.TCP_PROBE), ("NOZZLE", P.TCP_NOZZLE)):
        a(f"constexpr float TCP_{name}[3] = {{{m(v[0])}, {m(v[1])}, {m(v[2])}}};")
    a("// ---- joint limits (radians) ----")
    for name, v in (("YAW", P.LIM_YAW), ("SHOULDER", P.LIM_SHOULDER), ("ELBOW", P.LIM_ELBOW),
                    ("WRIST", P.LIM_WRIST), ("GRIP", P.LIM_GRIP)):
        a(f"constexpr float {name}_MIN = {rad(v[0])};")
        a(f"constexpr float {name}_MAX = {rad(v[1])};")
    a("// ---- gripper ----")
    a(f"constexpr float GRIP_PIVOT_HALF = {m(P.GRIP_DY)};   // finger pivots are +-this from the centre line")
    a(f"constexpr float GRIP_PAD_REACH = {m(P.L3 - P.GRIP_X)};    // pivot -> grasp centre")
    a(f"constexpr float GRIP_PAD_INSET = {m(P.GRIP_DY - 1.5)};    // pivot line -> pad face when closed")
    a("// ---- deck ----")
    a(f"constexpr float BASKET_X = {m(P.BASKET_X)};")
    a(f"constexpr float BASKET_Y = {m(P.BASKET_Y)};")
    a(f"constexpr float BASKET_RIM_Z = {m(P.DECK_TOP + P.BASKET_H)};")
    a("}  // namespace geom")
    a("}  // namespace agro")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
